import { spawnSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { sha256 } from "../src/hash.mjs";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(packageRoot, "schema-sources/authored/maataa-communications-v1");
const draft = JSON.parse(await readFile(path.join(sourceRoot, "contracts.draft.json"), "utf8"));
const plan = JSON.parse(await readFile(path.join(sourceRoot, "provider-enforcement-plan.json"), "utf8"));
if (draft.contractSetHash !== plan.contractSetHash) throw new Error("COMMUNICATIONS_ENFORCEMENT_PLAN_HASH_MISMATCH");

const cli = path.resolve(packageRoot, "../../node_modules/.bin/prisma");
for (const provider of ["postgresql", "sqlite"]) {
  const schemaPath = path.join(sourceRoot, `prisma-preview.${provider}.draft.prisma`);
  const relativeSchemaPath = path.relative(packageRoot, schemaPath);
  const configPath = `prisma.config.${provider}.ts`;
  const run = spawnSync(cli, ["migrate", "diff", "--from-empty", "--to-schema", relativeSchemaPath, "--script", "--config", configPath], { cwd: packageRoot, encoding: "utf8", maxBuffer: 20 * 1024 * 1024 });
  if (run.status !== 0 || !run.stdout?.trim()) throw new Error(`COMMUNICATIONS_${provider.toUpperCase()}_MIGRATION_DIFF_FAILED:${run.stderr ?? run.error?.message ?? "empty SQL"}`);
  const overlay = await readFile(path.join(sourceRoot, `provider-enforcement.${provider}.sql`), "utf8");
  const migrationSql = [
    `-- DRAFT PREVIEW ONLY · provider=${provider} · contractSetHash=${draft.contractSetHash}`,
    "-- Generated by Prisma Migrate diff from an empty schema, followed by the reviewed provider-invariant overlay.",
    "-- Do not execute without separate migration approval.",
    run.stdout.trimEnd(),
    "",
    "-- MAATAA invariant enforcement overlay",
    overlay.trim(),
    "",
  ].join("\n");
  const outputPath = path.join(sourceRoot, `migration-preview.${provider}.draft.sql`);
  await writeFile(outputPath, migrationSql);
  await writeFile(path.join(sourceRoot, `migration-preview.${provider}.draft.metadata.json`), `${JSON.stringify({
    schemaLifecycle: "DRAFT",
    contractSetHash: draft.contractSetHash,
    logicalSchemaHash: draft.readiness?.logicalSchemaHash ?? null,
    targetProvider: provider,
    generatedFrom: "Prisma Migrate diff --from-empty --to-schema --script plus reviewed MAATAA invariant overlay",
    migrationPreviewValid: true,
    migrationApproved: false,
    deploymentApproved: false,
    sqlSha256: sha256(migrationSql),
    basePrismaSqlSha256: sha256(run.stdout),
    overlaySqlSha256: sha256(overlay),
    overlayFile: `provider-enforcement.${provider}.sql`,
  }, null, 2)}\n`);
}
console.log(JSON.stringify({ context: "communications", contractSetHash: draft.contractSetHash, previews: ["postgresql", "sqlite"].map((provider) => `migration-preview.${provider}.draft.sql`), migrationApproved: false, deploymentApproved: false }, null, 2));

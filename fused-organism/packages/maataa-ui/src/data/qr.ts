/**
 * @maataa/ui/data/qr
 * QR Code encoder (ISO/IEC 18004), byte mode, versions 1–40, error
 * correction L/M/Q/H, automatic mask choice. No dependencies. Follows the
 * structure of Project Nayuki's reference implementation (MIT).
 */

export type QrErrorLevel = "L" | "M" | "Q" | "H";

const LEVEL_INDEX: Record<QrErrorLevel, number> = { L: 0, M: 1, Q: 2, H: 3 };
/** Format-info bits for each level */
const LEVEL_BITS: Record<QrErrorLevel, number> = { L: 1, M: 0, Q: 3, H: 2 };

